import { createHash as createHashChirho } from 'node:crypto';
import * as prettierChirho from 'prettier';
import { greekWordIpaChirho } from '../../src/lib/domain-chirho/pronunciation-chirho/greek-ipa-chirho';
import {
	nativeGreekGuideChirho,
	greekGuideCorpusChirho,
	greekGuidePartsChirho,
	loadGreekGuideChirho,
	GREEK_GUIDE_MANIFEST_CHIRHO,
	GREEK_GUIDE_PROFILES_CHIRHO,
	type GreekGuideManifestChirho,
	type GreekGuideRowChirho
} from '../../apps-chirho/ios-chirho/scripts-chirho/export_greek_ipa_chirho';

const rootChirho = resolveChirho(dirnameChirho(fileUrlToPathChirho(import.meta.url)), '../..');
const iosChirho =
	'apps-chirho/ios-chirho/HinnehCoreChirho/Sources/HinnehCoreChirho/ResourcesChirho';
const androidChirho = 'apps-chirho/android-chirho/app-chirho/src/main/assets';
const greekFoldersChirho = [
	iosChirho + '/greek-ipa-chirho',
	androidChirho + '/teaching-chirho/greek-ipa-chirho'
];
const legacyPathsChirho = [
	iosChirho + '/teaching-chirho.json',
	iosChirho + '/books-fallback-chirho.json',
	iosChirho + '/spoken-overrides-chirho.json',
	androidChirho + '/teaching-chirho/teaching-chirho.json',
	androidChirho + '/library-chirho/books-chirho.json',
	androidChirho + '/teaching-chirho/spoken-overrides-chirho.json'
];
const temporaryRootsChirho: string[] = [];
afterEachChirho(() => {
	for (const pathChirho of temporaryRootsChirho.splice(0))
		rmSyncChirho(pathChirho, { recursive: true, force: true });
});
let generatedChirho: Map<string, string>,
	manifestChirho: GreekGuideManifestChirho,
	actualChirho: Map<string, string>;
const digestChirho = (bytesChirho: Uint8Array | string) =>
	createHashChirho('sha256').update(bytesChirho).digest('hex');
beforeAllChirho(() => {
	generatedChirho = nativeGreekGuideChirho(rootChirho);
	manifestChirho = JSON.parse(generatedChirho.get(GREEK_GUIDE_MANIFEST_CHIRHO)!);
	actualChirho = new Map(
		[...generatedChirho.keys()].map((nameChirho) => [
			nameChirho,
			readFileSyncChirho(joinChirho(rootChirho, greekFoldersChirho[0], nameChirho), 'utf8')
		])
	);
}, 30000);
function syntheticGuideChirho(formsChirho: string[]) {
	const partsChirho = greekGuidePartsChirho(formsChirho),
		bytesChirho = new Map(
			partsChirho.map((partChirho) => [
				`greek-ipa-part-${String(partChirho.part_index_chirho).padStart(2, '0')}-chirho.json`,
				JSON.stringify(partChirho) + '\n'
			])
		);
	const changedManifestChirho = {
		...manifestChirho,
		form_count_chirho: formsChirho.length,
		parts_chirho: manifestChirho.parts_chirho.map((pinChirho, indexChirho) => {
			const textChirho = bytesChirho.get(pinChirho.file_chirho)!;
			return {
				...pinChirho,
				sha256_chirho: digestChirho(textChirho),
				bytes_chirho: Buffer.byteLength(textChirho),
				count_chirho: Object.keys(partsChirho[indexChirho].entries_chirho).length
			};
		})
	};
	return { manifest_chirho: JSON.stringify(changedManifestChirho), parts_chirho: bytesChirho };
}
describeChirho('source-bound native Greek teaching IPA', () => {
	itChirho(
		'both native bundles equal the generated bytes and every exact corpus form/profile equals the existing helper',
		() => {
			const inventoryChirho = greekGuideCorpusChirho(rootChirho);
			expectChirho(inventoryChirho.corpus_chirho.chapter_count_chirho).toBe(260);
			expectChirho(actualChirho.size).toBe(9);
			for (const [nameChirho, textChirho] of generatedChirho)
				for (const folderChirho of greekFoldersChirho)
					expectChirho(
						readFileSyncChirho(joinChirho(rootChirho, folderChirho, nameChirho), 'utf8')
					).toBe(textChirho);
			const lookupChirho = loadGreekGuideChirho(
				actualChirho.get(GREEK_GUIDE_MANIFEST_CHIRHO)!,
				actualChirho
			);
			expectChirho(manifestChirho.form_count_chirho).toBe(inventoryChirho.forms_chirho.length);
			const tableTextsChirho = manifestChirho.parts_chirho.flatMap((pinChirho) =>
				Object.values(
					JSON.parse(actualChirho.get(pinChirho.file_chirho)!).entries_chirho as Record<
						string,
						GreekGuideRowChirho
					>
				).map((rowChirho) => rowChirho.text_chirho)
			);
			expectChirho(new Set(tableTextsChirho)).toEqual(new Set(inventoryChirho.forms_chirho));
			for (const textChirho of inventoryChirho.forms_chirho)
				for (const profileChirho of GREEK_GUIDE_PROFILES_CHIRHO)
					expectChirho(lookupChirho(textChirho, profileChirho)).toBe(
						greekWordIpaChirho(textChirho, profileChirho)
					);
		},
		30000
	);
	itChirho(
		'preserves composed/decomposed byte identities and helper-null forms without profile fallback',
		() => {
			const composedChirho = 'Ἐν',
				decomposedChirho = composedChirho.normalize('NFD');
			expectChirho(digestChirho(composedChirho)).not.toBe(digestChirho(decomposedChirho));
			const fixtureChirho = syntheticGuideChirho([
				composedChirho,
				decomposedChirho,
				'unmapped-chirho'
			]);
			const lookupChirho = loadGreekGuideChirho(
				fixtureChirho.manifest_chirho,
				fixtureChirho.parts_chirho
			);
			for (const profileChirho of GREEK_GUIDE_PROFILES_CHIRHO) {
				expectChirho(lookupChirho(composedChirho, profileChirho)).toBe(
					greekWordIpaChirho(composedChirho, profileChirho)
				);
				expectChirho(lookupChirho(decomposedChirho, profileChirho)).toBe(
					greekWordIpaChirho(decomposedChirho, profileChirho)
				);
				expectChirho(lookupChirho('unmapped-chirho', profileChirho)).toBeNull();
			}
			expectChirho(lookupChirho('unknown-source-chirho', 'modern')).toBeNull();
			expectChirho(lookupChirho(composedChirho, 'toString' as 'modern')).toBeNull();
			expectChirho(lookupChirho('x'.repeat(1025), 'modern')).toBeNull();
		}
	);
	itChirho(
		'refuses corrupt bytes, changed schema, unsafe sizes and a rehashed foreign row identity',
		() => {
			const firstChirho = manifestChirho.parts_chirho[0];
			const corruptChirho = new Map(actualChirho);
			corruptChirho.set(firstChirho.file_chirho, corruptChirho.get(firstChirho.file_chirho)! + ' ');
			expectChirho(() =>
				loadGreekGuideChirho(actualChirho.get(GREEK_GUIDE_MANIFEST_CHIRHO)!, corruptChirho)
			).toThrow();
			expectChirho(() =>
				loadGreekGuideChirho(
					JSON.stringify({ ...manifestChirho, schema_version_chirho: 2 }),
					actualChirho
				)
			).toThrow();
			expectChirho(() =>
				loadGreekGuideChirho(
					JSON.stringify({
						...manifestChirho,
						parts_chirho: manifestChirho.parts_chirho.map((pinChirho, indexChirho) =>
							indexChirho ? pinChirho : { ...pinChirho, bytes_chirho: 1048577 }
						)
					}),
					actualChirho
				)
			).toThrow();
			const foreignChirho = JSON.parse(actualChirho.get(firstChirho.file_chirho)!);
			const keyChirho = Object.keys(foreignChirho.entries_chirho)[0];
			foreignChirho.entries_chirho[keyChirho].text_chirho = 'foreign-chirho';
			const changedTextChirho = JSON.stringify(foreignChirho) + '\n';
			const filesChirho = new Map(actualChirho);
			filesChirho.set(firstChirho.file_chirho, changedTextChirho);
			const changedManifestChirho = {
				...manifestChirho,
				parts_chirho: manifestChirho.parts_chirho.map((pinChirho, indexChirho) =>
					indexChirho
						? pinChirho
						: {
								...pinChirho,
								sha256_chirho: digestChirho(changedTextChirho),
								bytes_chirho: Buffer.byteLength(changedTextChirho)
							}
				)
			};
			expectChirho(() =>
				loadGreekGuideChirho(JSON.stringify(changedManifestChirho), filesChirho)
			).toThrow();
		}
	);
	itChirho('refuses canonical chapter-byte drift before producing a guide', () => {
		const scratchChirho = mkdtempSyncChirho(
			joinChirho(tmpdirChirho(), 'native-greek-ipa-source-chirho-')
		);
		temporaryRootsChirho.push(scratchChirho);
		symlinkSyncChirho(
			joinChirho(rootChirho, 'config-chirho'),
			joinChirho(scratchChirho, 'config-chirho'),
			'dir'
		);
		for (const pinChirho of [
			...manifestChirho.corpus_chirho.manifest_pins_chirho,
			...manifestChirho.corpus_chirho.chapter_pins_chirho
		]) {
			const relativeChirho = 'static' + pinChirho.path_chirho;
			mkdirSyncChirho(dirnameChirho(joinChirho(scratchChirho, relativeChirho)), {
				recursive: true
			});
			symlinkSyncChirho(
				joinChirho(rootChirho, relativeChirho),
				joinChirho(scratchChirho, relativeChirho)
			);
		}
		const relativeChirho =
			'static' + manifestChirho.corpus_chirho.chapter_pins_chirho[0].path_chirho;
		const changedChirho = joinChirho(scratchChirho, relativeChirho);
		unlinkSyncChirho(changedChirho);
		writeFileSyncChirho(
			changedChirho,
			readFileSyncChirho(joinChirho(rootChirho, relativeChirho), 'utf8') + ' '
		);
		expectChirho(() => nativeGreekGuideChirho(scratchChirho)).toThrow(
			'Canonical Greek chapter changed'
		);
	});
	itChirho(
		'the real exporter --check reports changed bundled bytes without rewriting any output',
		async () => {
			const scratchChirho = mkdtempSyncChirho(
				joinChirho(tmpdirChirho(), 'native-greek-ipa-check-chirho-')
			);
			temporaryRootsChirho.push(scratchChirho);
			for (const nameChirho of ['src', 'config-chirho', 'static', 'node_modules'])
				symlinkSyncChirho(
					joinChirho(rootChirho, nameChirho),
					joinChirho(scratchChirho, nameChirho),
					'dir'
				);
			const prettierOptionsChirho = await prettierChirho.resolveConfig(
				joinChirho(rootChirho, iosChirho, 'teaching-chirho.json')
			);
			writeFileSyncChirho(
				joinChirho(scratchChirho, '.prettierrc'),
				JSON.stringify(prettierOptionsChirho ?? {})
			);
			writeFileSyncChirho(joinChirho(scratchChirho, 'package.json'), '{"type":"module"}');
			writeFileSyncChirho(
				joinChirho(scratchChirho, 'tsconfig.json'),
				JSON.stringify({ compilerOptions: { paths: { '$lib/*': ['./src/lib/*'] } } })
			);
			for (const nameChirho of [
				'export_teaching_chirho.ts',
				'export_spoken_chirho.ts',
				'export_greek_ipa_chirho.ts'
			]) {
				const relativeChirho = 'apps-chirho/ios-chirho/scripts-chirho/' + nameChirho;
				mkdirSyncChirho(dirnameChirho(joinChirho(scratchChirho, relativeChirho)), {
					recursive: true
				});
				cpSyncChirho(
					joinChirho(rootChirho, relativeChirho),
					joinChirho(scratchChirho, relativeChirho)
				);
			}
			const outputsChirho = [
				...legacyPathsChirho,
				...greekFoldersChirho.flatMap((folderChirho) =>
					[...generatedChirho.keys()].map((nameChirho) => folderChirho + '/' + nameChirho)
				)
			];
			for (const relativeChirho of outputsChirho) {
				mkdirSyncChirho(dirnameChirho(joinChirho(scratchChirho, relativeChirho)), {
					recursive: true
				});
				cpSyncChirho(
					joinChirho(rootChirho, relativeChirho),
					joinChirho(scratchChirho, relativeChirho)
				);
			}
			const checkChirho = () =>
				spawnSyncChirho(
					'bun',
					[
						'--no-env-file',
						joinChirho(
							scratchChirho,
							'apps-chirho/ios-chirho/scripts-chirho/export_teaching_chirho.ts'
						),
						'--check'
					],
					{
						cwd: scratchChirho,
						encoding: 'utf8',
						env: { PATH: process.env.PATH, HOME: process.env.HOME },
						timeout: 30000,
						maxBuffer: 1048576
					}
				);
			const firstCheckChirho = checkChirho();
			expectChirho(firstCheckChirho.status, firstCheckChirho.stderr).toBe(0);
			const changedPathChirho = joinChirho(
				scratchChirho,
				greekFoldersChirho[0],
				manifestChirho.parts_chirho[0].file_chirho
			);
			writeFileSyncChirho(changedPathChirho, readFileSyncChirho(changedPathChirho, 'utf8') + ' ');
			const snapshotChirho = () =>
				outputsChirho.map((relativeChirho) => {
					const fullChirho = joinChirho(scratchChirho, relativeChirho);
					return {
						path_chirho: relativeChirho,
						sha256_chirho: digestChirho(readFileSyncChirho(fullChirho)),
						mtime_chirho: statSyncChirho(fullChirho).mtimeMs
					};
				});
			const beforeChirho = snapshotChirho();
			const refusedChirho = checkChirho();
			expectChirho(refusedChirho.status).toBe(1);
			expectChirho(refusedChirho.stderr).toContain(manifestChirho.parts_chirho[0].file_chirho);
			expectChirho(snapshotChirho()).toEqual(beforeChirho);
		},
		30000
	);
});
